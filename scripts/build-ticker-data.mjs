// Generates data/ticker-data.js: the few fields the site-wide ticker and footer
// need (name, league, value, five-year growth, data years, team count), so the
// app shell no longer loads the full team dataset on every route.
//
// Uses Vite's SSR loader because data/enrichments.js relies on import.meta.glob.
// Runs before `vite build` (see package.json) and can be run by hand:
//   node scripts/build-ticker-data.mjs
import fs from 'node:fs'
import { createServer } from 'vite'

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' })
try {
  const { default: teams } = await server.ssrLoadModule('/data/allTeams.js')
  const rows = [...teams]
    .sort((a, b) => b.currentValuation - a.currentValuation)
    .map((t) => ({ name: t.name, league: t.league, currentValuation: t.currentValuation, fiveYearGrowth: t.fiveYearGrowth }))
  const ys = teams.map((t) => t.valuationYear).filter(Boolean)
  const lo = Math.min(...ys), hi = Math.max(...ys)
  const years = lo === hi ? String(hi) : `${lo}–${hi}`
  const out = `// GENERATED by scripts/build-ticker-data.mjs from data/allTeams.js. Do not edit.
// Ticker rows are pre-sorted by currentValuation, highest first.
export const TEAM_COUNT = ${teams.length}
export const DATA_YEARS = ${JSON.stringify(years)}
export const tickerTeams = ${JSON.stringify(rows)}
`
  fs.writeFileSync('data/ticker-data.js', out)
  console.log(`data/ticker-data.js: ${rows.length} teams, ${(out.length / 1024).toFixed(1)} KB, years ${years}`)
} finally {
  await server.close()
}

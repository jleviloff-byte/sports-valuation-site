# Coverage report: which venues have a verified usable oblique photo, which are
# on a model path, and why. Writes docs/overhaul/coverage.md.
import json, os, re
V = json.load(open('data/stadiums.json'))['venues']
ICON = {x['slug'] for x in json.load(open('scripts/stadiums/overhaul/iconic.json'))}
VER = json.load(open('scripts/stadiums/refs/verified.json'))
TAILP = json.load(open('scripts/stadiums/overhaul/refpicks-tail.json'))
HITS = json.load(open('scripts/stadiums/overhaul/tail-aerial-hits.json'))
na = {}
for l in open('docs/overhaul/needs-attention.md'):
    m = re.match(r'\| ([a-z0-9-]+) \| (.+) \|\s*$', l)
    if m: na[m.group(1)] = m.group(2)
PILOT_PHOTO = {'fenway-park', 'wrigley-field', 'michigan-stadium', 'sofi-stadium'}
PILOT_MODEL = {'landn-federal-credit-union-stadium', 'lambeau-field', 'rupp-arena', 'q2-stadium', 'daytona-international-speedway',
               'madison-square-garden', 'arthur-ashe-stadium', 'bristol-motor-speedway'}
B1_PASS = set(json.load(open('scripts/stadiums/overhaul/picks-batch1.json')))
B1_FAIL3 = {'nissan-stadium', 'lincoln-financial-field', 'state-farm-stadium', 'neyland-stadium', 'target-field', 'rate-field',
            'raymond-james-stadium', 'chase-center', 'comerica-park', 'spartan-stadium'}
B1_BAD_REF = {'ford-field', 'united-center', 'talladega-superspeedway', 'crypto-com-arena', 'gaylord-family-oklahoma-memorial-stadium', 'pnc-park', 'progressive-field'}
SEG4 = {'lane-stadium', 'kenan-stadium', 'snapdragon-stadium', 'powers-field-at-princeton-stadium', 'washington-grizzly-stadium'}
CROPPED = {'firstbank-stadium', 'rynearson-stadium', 'fitton-field', 'delaware-stadium'}

def cls(s):
    if s in PILOT_PHOTO: return 'photo', 'pilot photo path; passed blind ID'
    if s in PILOT_MODEL: return 'pilot model', 'pilot hand-built 3D model from NAIP measurements (no usable aerial at pilot time)' + ('; ' + na[s] if s in na else '')
    if s in ICON:
        if s in B1_FAIL3: return 'generic', 'failed verification of output: verified oblique photo, but 3 generation attempts failed blind ID (photo low, partial or sign-heavy)'
        if s in B1_BAD_REF: return 'generic', 'wrong angle / unusable: ' + na.get(s, 'reference could not carry the venue')
        if s in B1_PASS: return 'photo', 'verified oblique photo; passed blind ID' + (' (provisional: photo predates rebuild)' if s in ('husky-stadium', 'notre-dame-stadium') else '')
        r = na.get(s, 'no usable aerial found in the Commons category crawl')
        kind = 'none found' if 'no aerial or elevated' in r else 'wrong angle' if re.search(r'interior|ground|tower|distant|engine|cut off|fills the aerial', r) else 'failed segmentation' if 'segment' in r else 'other'
        return 'generic', f'{kind}: {r}'
    if s in TAILP:
        if s in CROPPED: return 'generic', 'wrong angle: venue cut off at the photo edge'
        if s in SEG4: return 'photo', 'verified oblique photo; re-segmenting with a hand-marked box (not generated yet)'
        return 'photo', 'verified oblique photo; masked, generation not run yet'
    h = HITS.get(s)
    if h is None: return 'generic', 'none found: no Commons candidates were crawled for this venue'
    if h: return 'generic', 'wrong angle / rejected on review: aerial-keyword candidates were ground-level, distant, whole-circuit, outdated or mislabeled'
    return 'generic', 'none found by keyword: no Commons candidate titled, captioned or categorized as aerial (candidates not reviewed one by one)'

rows = [(v['slug'], v['name'], v['venue_type'], 'iconic' if v['slug'] in ICON else 'long tail', *cls(v['slug'])) for v in V]
cnt = {}
for r in rows: cnt[(r[3], r[4])] = cnt.get((r[3], r[4]), 0) + 1
out = ['# Coverage', '', 'Per-venue art path and the reason a venue has no usable photo. Generated by `scripts/stadiums/overhaul/coverage.py`.', '',
       '| group | photo path | pilot 3D model | generic model |', '|---|---|---|---|']
for g in ['iconic', 'long tail']:
    out.append(f"| {g} | {cnt.get((g, 'photo'), 0)} | {cnt.get((g, 'pilot model'), 0)} | {cnt.get((g, 'generic'), 0)} |")
out.append(f"| total | {sum(v for (g, p), v in cnt.items() if p == 'photo')} | {sum(v for (g, p), v in cnt.items() if p == 'pilot model')} | {sum(v for (g, p), v in cnt.items() if p == 'generic')} |")
out += ['', 'License: the candidate crawl only kept free-licensed files, so no venue is listed as excluded for license; non-free photos were never collected.',
        'Search depth so far: each venue\'s own Commons category plus a few keyword searches. Subcategories, Openverse, Flickr CC and US government archives have not been searched.', '',
        '| venue | type | group | path | reason |', '|---|---|---|---|---|']
for s, n, t, g, p, r in sorted(rows, key=lambda r: (r[3], r[4], r[0])): out.append(f'| {n} (`{s}`) | {t} | {g} | {p} | {r} |')
open('docs/overhaul/coverage.md', 'w').write('\n'.join(out) + '\n')
print({k: v for k, v in sorted(cnt.items())})
from collections import Counter
print(Counter((r[3], r[5].split(':')[0]) for r in rows if r[4] == 'generic'))
